// Step 2: Apply doctype schema (computed fields from user input)
await applyDoctypeSchema(doc, userInput);
// doc now has computed fields based on user changes

// Step 3: Apply system schema (overwrites system fields)
await applySystemSchema(doc);
// doc.modified = Date.now()
// doc.modified_by = currentUser
// System fields are SET, user input never touched them

// Step 4: Guardian validates
await applyGuardianSchema(doc);
// Throws if invalid

// Step 5: THEN adapter merges and saves
const finalDoc = { ...existingDoc, ...doc };
await adapter.update(finalDoc);

